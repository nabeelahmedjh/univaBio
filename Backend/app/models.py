"""SQLAlchemy ORM models: Doctor, Patient, Session.

Only three tables exist. The clinical report generated by the LLM is stored
directly on the Session as a single Markdown text column rather than a 4th table.
"""
from datetime import datetime, timezone
from typing import List, Optional

from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .database import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Doctor(Base):
    __tablename__ = "doctor"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    username: Mapped[str] = mapped_column(String(150), unique=True, index=True, nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    specialty: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)
    # Deactivated doctors cannot sign in or record sessions.
    active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)

    # One doctor -> many patients.
    patients: Mapped[List["Patient"]] = relationship(
        back_populates="doctor", cascade="all, delete-orphan"
    )


class Patient(Base):
    __tablename__ = "patient"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    # Public identifier used across the app; the patient looks up their record
    # by phone (patient id) without authenticating.
    phone: Mapped[str] = mapped_column(String(32), unique=True, index=True, nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    date_of_birth: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)
    gender: Mapped[Optional[str]] = mapped_column(String(32), nullable=True)

    # A patient has exactly one doctor.
    doctor_id: Mapped[int] = mapped_column(ForeignKey("doctor.id"), nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)

    doctor: Mapped["Doctor"] = relationship(back_populates="patients")
    # One patient -> many sessions.
    sessions: Mapped[List["Session"]] = relationship(
        back_populates="patient", cascade="all, delete-orphan"
    )

    @property
    def doctor_name(self) -> Optional[str]:
        """Convenience accessor so the API can expose the owning doctor's name."""
        return self.doctor.name if self.doctor else None


class Session(Base):
    """One consultation / follow-up visit between a doctor and a patient.

    Holds the conversation transcript and the embedded clinical report.
    """

    __tablename__ = "session"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    title: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    # Transcript of the conversation (speech-to-text handled elsewhere / later).
    transcript: Mapped[str] = mapped_column(Text, nullable=False)
    # Reserved for a future audio recording reference.
    audio_path: Mapped[Optional[str]] = mapped_column(String(512), nullable=True)
    # Length of the consultation recording in seconds (from the client, if known).
    duration_sec: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)

    # ---- Clinical report (a single Markdown document) ----
    # One of: "pending_key" | "generated" | "error"
    report_status: Mapped[str] = mapped_column(String(32), default="pending_key", nullable=False)
    # The report generated by the LLM, stored as Markdown text and rendered in the UI.
    report_markdown: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    report_error: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # A session belongs to one patient; the doctor is derived via patient.doctor.
    patient_id: Mapped[int] = mapped_column(ForeignKey("patient.id"), nullable=False, index=True)

    patient: Mapped["Patient"] = relationship(back_populates="sessions")
